#!/usr/bin/env python3
"""GitOps layout (#385): split the output of infra/ansible/render.yml into the Flux layers of a deployment repository.

Usage:
  scripts/gitops-layout.py <render_dir> <out_dir>
    <out_dir>/platform  every rendered object except Agent and Executor objects, plus kustomization.yaml
    <out_dir>/agents    Agent and Executor objects (#58), plus kustomization.yaml
The infrastructure layer (ESO, Reloader) is static: examples/deployment/gcp-gke/gitops/flux/infrastructure.

Rules of the engine (#385):
  - spec.replicas is removed from every StatefulSet. The router owns the replicas of agent StatefulSets, so no
    StatefulSet replicas are in Git. A platform StatefulSet gets the Kubernetes default (1).
  - an object that the render writes twice (deploy.yml merges them, for example the executors Namespace) is merged
    into its last place, the later fields win; kustomize and Flux refuse a duplicate.
  - no Secret is written. The render never has one; the script refuses one, so a value never reaches Git.
<out_dir> must be absent or empty, so a removed object leaves Git and the engine prunes it. Needs PyYAML.
"""
import glob
import os
import shutil
import sys

import yaml

AGENT_KINDS = {"Agent", "Executor"}


def merge(a, b):
    if isinstance(a, dict) and isinstance(b, dict):
        out = dict(a)
        for k, v in b.items():
            out[k] = merge(a[k], v) if k in a else v
        return out
    return b


def key(doc):
    md = doc.get("metadata") or {}
    return (doc.get("apiVersion", "").split("/")[0], doc.get("kind"), md.get("namespace", ""), md.get("name"))


def main(argv):
    if len(argv) != 3 or not os.path.isdir(argv[1]):
        sys.stderr.write("usage: gitops-layout.py <render_dir> <out_dir>\n")
        return 2
    src, out = argv[1], argv[2]
    if os.path.isdir(out) and os.listdir(out):
        sys.stderr.write(f"ERROR: {out} is not empty\n")
        return 2
    files = sorted(glob.glob(os.path.join(src, "[0-9][0-9]-*.yaml")))
    if not files:
        sys.stderr.write(f"ERROR: no rendered NN-*.yaml file in {src}\n")
        return 2
    docs = []  # (file, doc)
    for f in files:
        with open(f, encoding="utf-8") as fh:
            for d in yaml.safe_load_all(fh):
                if d:
                    docs.append((os.path.basename(f), d))
    if any(d.get("kind") == "Secret" for _, d in docs):
        sys.stderr.write("ERROR: the render output has a Secret; refusing to write it to Git\n")
        return 1
    merged, last = {}, {}
    for i, (_, d) in enumerate(docs):
        k = key(d)
        merged[k] = merge(merged[k], d) if k in merged else d
        last[k] = i
    layers = {"platform": {}, "agents": {}}
    for i, (name, d) in enumerate(docs):
        k = key(d)
        if last[k] != i:
            continue
        d = merged[k]
        if d.get("kind") == "StatefulSet":
            d.get("spec", {}).pop("replicas", None)
        layer = "agents" if d.get("kind") in AGENT_KINDS else "platform"
        layers[layer].setdefault(name, []).append(d)
    for layer, by_file in layers.items():
        d_out = os.path.join(out, layer)
        os.makedirs(d_out, exist_ok=True)
        for name, items in by_file.items():
            with open(os.path.join(d_out, name), "w", encoding="utf-8") as fh:
                yaml.safe_dump_all(items, fh, sort_keys=False, default_flow_style=False, width=120)
        with open(os.path.join(d_out, "kustomization.yaml"), "w", encoding="utf-8") as fh:
            fh.write("# Generated by agentdev scripts/gitops-layout.py (#385) from render.yml output. Do not edit.\n")
            yaml.safe_dump({"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization",
                            "resources": sorted(by_file)}, fh, sort_keys=False)
    if os.path.isfile(os.path.join(src, "SECRETS.md")):
        shutil.copy(os.path.join(src, "SECRETS.md"), os.path.join(out, "SECRETS.md"))
    print(f"Wrote {out}/platform and {out}/agents")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
