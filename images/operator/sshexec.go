package main

// SSH credentials of executor runs (#204, docs/adr/0007, ADR 0003 D5). For an Executor with spec.ssh:
//
//   - pr stage (unreviewed head): no SSH at all. spec.prPlan runs instead of spec.plan, no Secret, no ProxyCommand,
//     and the egress proxy rule for port 22 is never reached because the PR Job has no config pointing there.
//   - merge stage: a fresh ed25519 key with a certificate of principal agentdev-<executor>-check, user agentdev-check.
//   - apply stage: a fresh key with principal agentdev-<executor>-apply, user agentdev (sudo on the server).
//
// The certificate is valid 15 minutes (the CA's maximum) from the start of the Job, key ID executor/<run>/<commit>.
// Key, certificate, known_hosts (@cert-authority of the host CA, per target name) and an ssh_config live in Secret
// <run>-ssh, owned by the ExecutorRun (deleted with it), mounted read-only only in the tool container. The ssh_config sends
// every connection through connect-proxy and the executor egress proxy; StrictHostKeyChecking yes, no TOFU.

import (
	"context"
	"crypto/ed25519"
	"encoding/pem"
	"errors"
	"fmt"
	"regexp"
	"sort"
	"strings"
	"time"

	"golang.org/x/crypto/ssh"
	batchv1 "k8s.io/api/batch/v1"
	corev1 "k8s.io/api/core/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/utils/ptr"
	"sigs.k8s.io/controller-runtime/pkg/client"
	"sigs.k8s.io/controller-runtime/pkg/controller/controllerutil"

	v1 "github.com/valentinalexeev/agentdev/images/operator/api/v1alpha1"
)

// sshHostRE is the CRD pattern of SSHTarget spec.host, checked again before a host reaches ssh_config.
var sshHostRE = regexp.MustCompile(`^(([a-z0-9]([-a-z0-9]*[a-z0-9])?\.)*[a-z0-9]([-a-z0-9]*[a-z0-9])?|[0-9]{1,3}(\.[0-9]{1,3}){3})$`)

const (
	sshDir        = "/ssh"      // the run's Secret in the tool container
	sshHelperDir  = "/agentdev" // connect-proxy (the operator binary) in the tool container
	sshCertTTL    = 15 * time.Minute
	sshInventory  = sshDir + "/inventory.ini"
	sshConfigFile = sshDir + "/config"
)

// sshTargetsOf lists the Ready SSHTargets of an executor, sorted by name.
func (p *ExecutorPoller) sshTargetsOf(ctx context.Context, e *v1.Executor) ([]v1.SSHTarget, error) {
	var list v1.SSHTargetList
	if err := p.Direct.List(ctx, &list, client.InNamespace(p.C.NS)); err != nil {
		return nil, err
	}
	var out []v1.SSHTarget
	for _, t := range list.Items {
		if t.Spec.Executor == e.Name && t.Status.Phase == "Ready" && t.Status.HostCAKey != "" && sshHostRE.MatchString(t.Spec.Host) {
			out = append(out, t)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

func sshPort(t *v1.SSHTarget) int {
	if t.Spec.Port == 0 {
		return 22
	}
	return int(t.Spec.Port)
}

// sshRunFiles renders the Secret data of one run (pure; tested). user is the local user of the stage.
func sshRunFiles(targets []v1.SSHTarget, user string, priv ed25519.PrivateKey, cert *ssh.Certificate) (map[string][]byte, error) {
	if len(targets) == 0 {
		return nil, errors.New("no Ready SSHTarget for this executor")
	}
	block, err := ssh.MarshalPrivateKey(priv, "")
	if err != nil {
		return nil, err
	}
	var known, cfg, inv strings.Builder
	cfg.WriteString("# agentdev executor run (#204): generated by the operator\n")
	inv.WriteString("[agentdev]\n")
	for _, t := range targets {
		if !sshHostRE.MatchString(t.Spec.Host) {
			return nil, fmt.Errorf("SSHTarget %s: invalid host", t.Name)
		}
		ca := strings.TrimSpace(t.Status.HostCAKey)
		if _, _, _, _, err := ssh.ParseAuthorizedKey([]byte(ca)); err != nil {
			return nil, fmt.Errorf("SSHTarget %s: host CA key: %w", t.Name, err)
		}
		// HostKeyAlias is used as the known_hosts name (no port), so one line per alias
		fmt.Fprintf(&known, "@cert-authority %s %s\n", t.Spec.Host, ca)
		// HostKeyAlias: the host certificate must name spec.host, whatever address the connection goes to
		fmt.Fprintf(&cfg, "Host %s\n  HostName %s\n  Port %d\n  HostKeyAlias %s\n", t.Spec.Host, t.Spec.Host, sshPort(&t), t.Spec.Host)
		fmt.Fprintf(&inv, "%s ansible_host=%s ansible_port=%d\n", t.Name, t.Spec.Host, sshPort(&t))
	}
	fmt.Fprintf(&cfg, "Host *\n  User %s\n  IdentityFile %s/id_ed25519\n  CertificateFile %s/id_ed25519-cert.pub\n"+
		"  IdentitiesOnly yes\n  UserKnownHostsFile %s/known_hosts\n  GlobalKnownHostsFile /dev/null\n"+
		"  StrictHostKeyChecking yes\n  HostKeyAlgorithms ssh-ed25519-cert-v01@openssh.com\n  CheckHostIP no\n"+
		"  ProxyCommand %s/agentdev-operator connect-proxy %%h %%p\n  ForwardAgent no\n  ForwardX11 no\n"+
		"  ControlMaster no\n  BatchMode yes\n  ConnectTimeout 20\n  RequestTTY no\n",
		user, sshDir, sshDir, sshDir, sshHelperDir)
	return map[string][]byte{
		"id_ed25519":          pem.EncodeToMemory(block),
		"id_ed25519-cert.pub": ssh.MarshalAuthorizedKey(cert),
		"known_hosts":         []byte(known.String()),
		"config":              []byte(cfg.String()),
		"inventory.ini":       []byte(inv.String()),
		// OpenSSH refuses to run for a uid without a passwd entry; the tool runs as 1000 in any image
		"passwd": []byte("root:x:0:0:root:/root:/sbin/nologin\nexecutor:x:1000:1000:agentdev executor:/work/home:/bin/sh\n"),
		"group":  []byte("root:x:0:\nexecutor:x:1000:\n"),
	}, nil
}

// sshStage returns principal, user and whether the stage gets SSH at all.
func sshStage(e *v1.Executor, r *v1.ExecutorRun, t *v1.SSHTarget) (principal, user string, ok bool) {
	switch {
	case !e.Spec.SSH || r.Spec.Stage == "pr":
		return "", "", false
	case r.Spec.Stage == "merge" && r.Spec.Action == "plan",
		r.Spec.Stage == "snapshot" && r.Spec.Action == "snapshot", // read-only: the check user, never sudo
		r.Spec.Stage == "drift" && r.Spec.Action == "plan":
		return "agentdev-" + e.Name + "-check", checkUser(t), true
	case r.Spec.Stage == "apply" && r.Spec.Action == "apply":
		return "agentdev-" + e.Name + "-apply", applyUser(t), true
	}
	return "", "", false
}

// sshSecretName is the per-run Secret.
func sshSecretName(r *v1.ExecutorRun) string { return r.Name + "-ssh" }

// ensureRunSSH makes the run's SSH Secret before its Job starts. All targets of the executor must use the same
// local user names (checked: one certificate, one ssh_config User). Returns false when the stage has no SSH.
func (p *ExecutorPoller) ensureRunSSH(ctx context.Context, e *v1.Executor, r *v1.ExecutorRun) (bool, error) {
	if !e.Spec.SSH || r.Spec.Stage == "pr" {
		return false, nil
	}
	if p.SSHCA == nil {
		return false, errors.New("spec.ssh is set but the SSH CA is not configured (scripts/ssh-ca-init.sh)")
	}
	targets, err := p.sshTargetsOf(ctx, e)
	if err != nil {
		return false, err
	}
	if len(targets) == 0 {
		return false, errors.New("spec.ssh is set but the executor has no Ready SSHTarget")
	}
	principal, user, ok := sshStage(e, r, &targets[0])
	if !ok {
		return false, nil
	}
	for i := range targets {
		if _, u, _ := sshStage(e, r, &targets[i]); u != user {
			return false, fmt.Errorf("SSHTargets of executor %s use different local users (%s, %s)", e.Name, user, u)
		}
	}
	var existing corev1.Secret
	if err := p.Direct.Get(ctx, client.ObjectKey{Namespace: p.C.NS, Name: sshSecretName(r)}, &existing); err == nil {
		return true, nil // made by an earlier pass; single use like the run
	} else if !apierrors.IsNotFound(err) {
		return false, err
	}
	ca, err := p.SSHCA(ctx)
	if err != nil {
		return false, err
	}
	keyID := "executor/" + r.Name + "/" + r.Spec.Commit
	if r.Spec.Stage == "snapshot" {
		keyID = "snapshot/" + r.Name
	}
	if r.Spec.Stage == "probe" {
		return false, errors.New("probe runs get no Job")
	}
	priv, _, cert, err := newCertKey(ctx, ca, SSHCertRequest{Type: "user", KeyID: keyID,
		Principals: []string{principal}, Validity: sshCertTTL})
	if err != nil {
		return false, fmt.Errorf("SSH certificate: %w", err)
	}
	data, err := sshRunFiles(targets, user, priv, cert)
	if err != nil {
		return false, err
	}
	sec := &corev1.Secret{ObjectMeta: metav1.ObjectMeta{Name: sshSecretName(r), Namespace: p.C.NS,
		Labels: map[string]string{"app": "agentdev-executor-ssh", "agentdev/executor": e.Name}}, Data: data}
	// owned by the run: deleted with it (retention); the certificate is expired 15 minutes after the start anyway
	if err := controllerutil.SetControllerReference(r, sec, p.Scheme()); err != nil {
		return false, err
	}
	if err := p.Create(ctx, sec); err != nil && !apierrors.IsAlreadyExists(err) {
		return false, err
	}
	return true, nil
}

// addRunSSH mounts the run's SSH Secret and connect-proxy into the tool container of a rendered Job. The Secret is
// mounted only there (not in checkout or the hash/verify helpers); the helper binary comes from the operator image.
func (p *ExecutorPoller) addRunSSH(job *batchv1.Job, r *v1.ExecutorRun) {
	spec := &job.Spec.Template.Spec
	spec.Volumes = append(spec.Volumes,
		corev1.Volume{Name: "ssh", VolumeSource: corev1.VolumeSource{Secret: &corev1.SecretVolumeSource{
			SecretName: sshSecretName(r), DefaultMode: ptr.To[int32](0o440)}}},
		corev1.Volume{Name: "agentdev-bin", VolumeSource: corev1.VolumeSource{EmptyDir: &corev1.EmptyDirVolumeSource{}}})
	// the operator's own image, as the hash/verify helpers (snapshot Jobs have neither)
	helperImage, pull := p.C.HelperImage, p.C.PullPolicy
	sc := &corev1.SecurityContext{RunAsUser: ptr.To[int64](1000), RunAsGroup: ptr.To[int64](1000), RunAsNonRoot: ptr.To(true),
		AllowPrivilegeEscalation: ptr.To(false), ReadOnlyRootFilesystem: ptr.To(true),
		Capabilities: &corev1.Capabilities{Drop: []corev1.Capability{"ALL"}}}
	res := res("10m", "32Mi", "500m", "128Mi")
	tool := func(cs []corev1.Container) *corev1.Container {
		for i := range cs {
			if cs[i].Name == "tool" {
				return &cs[i]
			}
		}
		return nil
	}
	install := corev1.Container{Name: "ssh-helper", Image: helperImage, ImagePullPolicy: corev1.PullPolicy(pull),
		Args:            []string{"install-helper", sshHelperDir + "/agentdev-operator"},
		VolumeMounts:    []corev1.VolumeMount{{Name: "agentdev-bin", MountPath: sshHelperDir}},
		SecurityContext: sc, Resources: res}
	// right after checkout and before the tool (an init container on plan runs), so the tool finds it
	at := 0
	for i, c := range spec.InitContainers {
		if c.Name == "checkout" {
			at = i + 1
		}
	}
	spec.InitContainers = append(spec.InitContainers[:at], append([]corev1.Container{install}, spec.InitContainers[at:]...)...)
	t := tool(spec.InitContainers)
	if t == nil {
		t = tool(spec.Containers)
	}
	t.VolumeMounts = append(t.VolumeMounts,
		corev1.VolumeMount{Name: "ssh", MountPath: sshDir, ReadOnly: true},
		corev1.VolumeMount{Name: "ssh", MountPath: "/etc/passwd", SubPath: "passwd", ReadOnly: true},
		corev1.VolumeMount{Name: "ssh", MountPath: "/etc/group", SubPath: "group", ReadOnly: true},
		corev1.VolumeMount{Name: "agentdev-bin", MountPath: sshHelperDir, ReadOnly: true})
	t.Env = append(t.Env,
		corev1.EnvVar{Name: "AGENTDEV_SSH_CONFIG", Value: sshConfigFile},
		corev1.EnvVar{Name: "AGENTDEV_SSH_INVENTORY", Value: sshInventory},
		corev1.EnvVar{Name: "GIT_SSH_COMMAND", Value: "ssh -F /dev/null -o BatchMode=yes -o StrictHostKeyChecking=yes"}, // no server config for git
		corev1.EnvVar{Name: "ANSIBLE_SSH_ARGS", Value: "-F " + sshConfigFile},
		corev1.EnvVar{Name: "ANSIBLE_HOST_KEY_CHECKING", Value: "True"},
		corev1.EnvVar{Name: "ANSIBLE_SSH_PIPELINING", Value: "True"},
		corev1.EnvVar{Name: "ANSIBLE_SSH_USETTY", Value: "False"}) // the certificates permit no PTY
}

// applyUser is the local user for the apply stage (default agentdev).
func applyUser(t *v1.SSHTarget) string {
	if t.Spec.ApplyUser == "" {
		return "agentdev"
	}
	return t.Spec.ApplyUser
}
