package main

// Executor egress (#135, docs/security-model.md phase 5). Executor Jobs reach the outside only through the executor
// egress proxy in EXEC_NS (manifests/executor-egress.yaml.tmpl): the NetworkPolicy executor-egress allows them DNS,
// the proxy, the in-cluster forge and the GKE metadata server (Workload Identity), nothing else. The proxy allows
// each executor only its own hosts:
//
//   - the operator keeps Secret executor-egress-proxy: one random key per Executor (key-<name>) and the Squid include
//     acl.conf that binds the proxy credential <name>:<key> to the executor's hosts (EXECUTOR_EGRESS_HOSTS, the
//     forge's git host and spec.egressHosts). The proxy reloads when acl.conf changes.
//   - the Job's checkout and tool containers get HTTPS_PROXY with that credential (from the Secret by the kubelet).
//     A key opens only its own executor's hosts, so a PR that reads it gains nothing.
//   - every refused request is one AGENTDEV_SECURITY_EVENT line of the proxy; the poller reads them and records a
//     SecurityEvent of the executor whose pod had the client IP (source egress, rule egress-host): one per run, host
//     and 10-minute window, at most SECURITY_RATE_BURST hosts per run and window, then one rate-limited event. PR
//     code controls the requests, so it must not be able to flood the event store; dropped lines are counted.

