// +kubebuilder:rbac:groups="",resources=secrets,verbs=create
// +kubebuilder:rbac:groups="",resources=secrets,verbs=get;update,resourceNames=executor-egress-proxy

const (
	execEgressSecret = "executor-egress-proxy" // operator-owned: per-executor keys and the Squid acl include
	execEgressApp    = "executor-egress-proxy" // app label of the proxy pods (manifests/executor-egress.yaml.tmpl)
	execEgressACL    = "acl.conf"
	execNoProxy      = "localhost,127.0.0.1,::1,.svc,.svc.cluster.local,.cluster.local,169.254.169.254,metadata.google.internal"
)

// egressHostRE is the CRD pattern of spec.egressHosts (and of EXECUTOR_EGRESS_HOSTS): a DNS name, optionally with a
// leading dot. Checked again before a host reaches squid.conf (fail closed if the CRD was changed or bypassed).
var egressHostRE = regexp.MustCompile(`^\.?([a-z0-9]([-a-z0-9]*[a-z0-9])?\.)+[a-z]([-a-z0-9]*[a-z0-9])?$`)

// egressHosts is the sorted allow-list of one executor: defaults, the forge's git host (when it is not an
// in-cluster name, which goes direct) and spec.egressHosts. Invalid entries are dropped.
func (p *ExecutorPoller) egressHosts(e *v1.Executor) []string {
	seen := map[string]bool{}
	var out []string
	add := func(h string) {
		h = strings.ToLower(strings.TrimSpace(h))
		if !egressHostRE.MatchString(h) || len(h) > 253 || seen[h] {
			return
		}
		seen[h] = true
		out = append(out, h)
	}
	for _, h := range p.C.EgressHosts {
		add(h)
	}
	if u, err := url.Parse(p.gitBase(e)); err == nil && !inCluster(u.Hostname()) {
		add(u.Hostname())
	}
	for _, h := range e.Spec.EgressHosts {
		add(h)
	}
	sort.Strings(out)
	return out
}

func inCluster(host string) bool {
	return host == "localhost" || strings.HasSuffix(host, ".svc") || strings.HasSuffix(host, ".cluster.local") ||
		!strings.Contains(host, ".")
}

// egressACL renders the Squid include for the given executors and keys. Only lines this function writes reach
// squid.conf: names match the CRD's name rule, hosts egressHostRE, keys are hex.
func egressACL(execs []v1.Executor, keys map[string]string, hosts func(*v1.Executor) []string) string {
	var b strings.Builder
	b.WriteString("# generated by agentdev-operator (#135): one credential and host list per Executor\n")
	for i := range execs {
		e := &execs[i]
		k := keys[e.Name]
		hs := hosts(e)
		if k == "" || len(hs) == 0 || !execNameRE.MatchString(e.Name) {
			continue
		}
		id := strings.ReplaceAll(e.Name, "-", "_")
		cred := regexp.QuoteMeta(base64.StdEncoding.EncodeToString([]byte(e.Name + ":" + k)))
		fmt.Fprintf(&b, "acl exec_%s_client req_header Proxy-Authorization ^Basic.%s$\n", id, cred)
		fmt.Fprintf(&b, "acl exec_%s_hosts dstdomain -n %s\n", id, strings.Join(hs, " "))
		fmt.Fprintf(&b, "http_access allow exec_%s_client exec_%s_hosts\n", id, id)
	}
	return b.String()
}

var execNameRE = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]*[a-z0-9])?$`)

// syncEgress keeps Secret executor-egress-proxy in step with the Executors that may run (valid, owner of their
// environment): a key for each (kept across passes), none for others, and acl.conf. Off without EgressProxy.
func (p *ExecutorPoller) syncEgress(ctx context.Context, items []v1.Executor, owner map[string]string) error {
	if p.C.EgressProxy == "" {
		return nil
	}
	var sec corev1.Secret
	err := p.Direct.Get(ctx, types.NamespacedName{Namespace: p.C.NS, Name: execEgressSecret}, &sec)
	create := apierrors.IsNotFound(err)
	if err != nil && !create {
		return err
	}
	var live []v1.Executor
	keys := map[string]string{}
	for i := range items {
		e := items[i]
		if owner[e.Spec.Environment] != e.Name || validExecutor(&e) != "" {
			continue
		}
		k := string(sec.Data["key-"+e.Name])
		if !hexKeyRE.MatchString(k) {
			var b [24]byte
			if _, err := rand.Read(b[:]); err != nil {
				return err
			}
			k = hex.EncodeToString(b[:])
		}
		keys[e.Name] = k
		live = append(live, e)
	}
	sort.Slice(live, func(i, j int) bool { return live[i].Name < live[j].Name })
	data := map[string][]byte{execEgressACL: []byte(egressACL(live, keys, p.egressHosts))}
	for n, k := range keys {
		data["key-"+n] = []byte(k)
	}
	if create {
		sec = corev1.Secret{ObjectMeta: metav1.ObjectMeta{Name: execEgressSecret, Namespace: p.C.NS,
			Labels: map[string]string{"app": execEgressApp}}, Data: data}
		return p.Create(ctx, &sec)
	}
	if equalBytes(sec.Data, data) {
		return nil
	}
	sec.Data, sec.StringData = data, nil
	return p.Update(ctx, &sec)
}

var hexKeyRE = regexp.MustCompile(`^[0-9a-f]{48}$`)

func equalBytes(a, b map[string][]byte) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		if w, ok := b[k]; !ok || string(w) != string(v) {
			return false
		}
	}
	return true
}

// egressEnv is the proxy environment of the Job's checkout and tool containers: the executor's credential from
// Secret executor-egress-proxy (expanded by the kubelet; EXEC_EGRESS_KEY must come first). Empty without a proxy.
func (p *ExecutorPoller) egressEnv(e *v1.Executor) []corev1.EnvVar {
	if p.C.EgressProxy == "" {
		return nil
	}
	proxy := strings.Replace(p.C.EgressProxy, "://", "://"+e.Name+":$(EXEC_EGRESS_KEY)@", 1)
	out := []corev1.EnvVar{{Name: "EXEC_EGRESS_KEY", ValueFrom: &corev1.EnvVarSource{SecretKeyRef: &corev1.SecretKeySelector{
		LocalObjectReference: corev1.LocalObjectReference{Name: execEgressSecret}, Key: "key-" + e.Name}}}}
	for _, k := range []string{"HTTPS_PROXY", "HTTP_PROXY", "https_proxy", "http_proxy"} {
		out = append(out, corev1.EnvVar{Name: k, Value: proxy})
	}
	return append(out, corev1.EnvVar{Name: "NO_PROXY", Value: execNoProxy}, corev1.EnvVar{Name: "no_proxy", Value: execNoProxy})
}

// sinceLogs reads a container's log (with timestamps) from since, without following.
type sinceLogs func(ctx context.Context, ns, pod, container string, since *metav1.Time) (io.ReadCloser, error)

func kubeSinceLogs(cs kubernetes.Interface) sinceLogs {
	return func(ctx context.Context, ns, pod, container string, since *metav1.Time) (io.ReadCloser, error) {
		return cs.CoreV1().Pods(ns).GetLogs(pod, &corev1.PodLogOptions{Container: container, Timestamps: true,
			SinceTime: since}).Stream(ctx)
	}
}

// collectEgress turns the executor proxy's refusal lines since the last pass into SecurityEvents of the executor
// whose pod made the request. Names are derived from the line, so a line read twice (operator restart) is one event.
func (p *ExecutorPoller) collectEgress(ctx context.Context, items []v1.Executor) {
	if p.C.EgressProxy == "" || p.EgressLogs == nil {
		return
	}
	var proxies, pods corev1.PodList
	if err := p.Direct.List(ctx, &proxies, client.InNamespace(p.C.NS), client.MatchingLabels{"app": execEgressApp}); err != nil {
		log.FromContext(ctx).Error(err, "list executor egress proxy pods")
		return
	}
	if err := p.Direct.List(ctx, &pods, client.InNamespace(p.C.NS), client.MatchingLabels{"app": "agentdev-executor"}); err != nil {
		log.FromContext(ctx).Error(err, "list executor pods")
		return
	}
	byName := map[string]*v1.Executor{}
	for i := range items {
		byName[items[i].Name] = &items[i]
	}
	if p.egressSince == nil {
		p.egressSince = map[types.UID]time.Time{}
	}
	for i := range proxies.Items {
		px := &proxies.Items[i]
		if px.Status.Phase != corev1.PodRunning {
			continue
		}
		var since *metav1.Time
		if t, ok := p.egressSince[px.UID]; ok {
			since = &metav1.Time{Time: t}
		}
		rc, err := p.EgressLogs(ctx, p.C.NS, px.Name, "squid", since)
		if err != nil {
			log.FromContext(ctx).V(1).Info("open executor proxy log", "err", err.Error())
			continue
		}
		last := p.consumeEgress(ctx, rc, px, pods.Items, byName)
		rc.Close()
		if !last.IsZero() {
			p.egressSince[px.UID] = last
		}
	}
	if n := p.EgressDropped.Load(); n > 0 {
		log.FromContext(ctx).V(1).Info("executor egress refusals not recorded as their own event (total since start)", "dropped", n)
	}
}

// consumeEgress records the refusal lines of one proxy log; returns the time of the last line read.
func (p *ExecutorPoller) consumeEgress(ctx context.Context, r io.Reader, px *corev1.Pod, pods []corev1.Pod, byName map[string]*v1.Executor) time.Time {
	var last time.Time
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 64*1024), 1024*1024)
	for sc.Scan() {
		ts, rest, ok := strings.Cut(strings.TrimRight(sc.Text(), "\r\n"), " ")
		t, err := time.Parse(time.RFC3339Nano, ts)
		if !ok || err != nil {
			continue
		}
		last = t
		if !strings.HasPrefix(rest, eventPrefix) {
			continue
		}
		var ev struct {
			Rule, Severity, Client, Action string
		}
		if json.Unmarshal([]byte(strings.TrimPrefix(rest, eventPrefix)), &ev) != nil || ev.Client == "" {
			continue
		}
		var pod *corev1.Pod
		for i := range pods {
			if pods[i].Status.PodIP == ev.Client && (pod == nil || pods[i].Status.Phase == corev1.PodRunning) {
				pod = &pods[i]
			}
		}
		if pod == nil {
			log.FromContext(ctx).Info("executor egress refusal from a client that is no executor pod", "action", clip(ev.Action, 200))
			continue
		}
		e := byName[pod.Labels["agentdev/executor"]]
		if e == nil {
			continue
		}
		job := pod.Labels["job-name"]
		host := egressHostOf(ev.Action)
		win := t.Truncate(p.egressWindow())
		rec, first := p.admitEgress(e.Name+"/"+job, host, win)
		if !rec && !first {
			p.EgressDropped.Add(1)
			continue
		}
		// one event per executor run (Job), host and window: the name is derived from them, so a line read twice
		// (operator restart) or the next refusal of the same host in the window is the same event.
		h := sha256.Sum256([]byte(e.Name + "\x00" + job + "\x00" + host + "\x00" + win.UTC().Format(time.RFC3339)))
		spec := v1.SecurityEventSpec{Schema: v1.SchemaV1, Source: "egress", Rule: "egress-host", Severity: "medium",
			Agent: e.Name, Job: job, Action: clip(ev.Action, 503), Time: metav1.NewTime(t), Pod: pod.Name,
			Container: execEgressApp, Hash: hex.EncodeToString(h[:])}
		if !rec { // first refusal over the cap in this window: one rate-limited event, the rest are dropped
			p.EgressDropped.Add(1)
			hr := sha256.Sum256([]byte(e.Name + "\x00" + job + "\x00" + win.UTC().Format(time.RFC3339)))
			spec.Hash = hex.EncodeToString(hr[:])
			spec = rateLimited(spec, p.egressCap())
			spec.Action = fmt.Sprintf("more than %d refused hosts in %s from executor run %s; further refusals dropped",
				p.egressCap(), p.egressWindow(), job)
		}
		if !jobRE.MatchString(spec.Job) {
			spec.Job = "" // Job names are <executor>-<stage>-...; the event store keeps issue-/pr- job ids only
		}
		if err := p.recordSpec(ctx, spec); err != nil {
			log.FromContext(ctx).Error(err, "record executor egress refusal")
		}
	}
	return last
}

// egressHostOf is the target host of a refused request ("CONNECT host:443" or "GET http://host/path").
func egressHostOf(action string) string {
	f := strings.Fields(action)
	if len(f) < 2 {
		return ""
	}
	t := f[1]
	if u, err := url.Parse(t); err == nil && strings.Contains(t, "://") {
		return strings.ToLower(u.Hostname())
	}
	if h, _, ok := strings.Cut(t, ":"); ok {
		t = h
	}
	return strings.ToLower(clip(t, 253))
}

func (p *ExecutorPoller) egressWindow() time.Duration {
	if p.C.EgressWindow > 0 {
		return p.C.EgressWindow
	}
	return 10 * time.Minute
}

func (p *ExecutorPoller) egressCap() int {
	if p.C.EgressMaxEvents > 0 {
		return p.C.EgressMaxEvents
	}
	return 20
}

// egressAgg is the flood state of one executor run (executor/Job) in one window: hosts already recorded and whether
// the rate-limited event was written.
type egressAgg struct {
	win     time.Time
	hosts   map[string]bool
	limited bool
}

// admitEgress decides on one refusal: rec=true for the first refusal of a host in the window (record it), as long as
// the run has fewer than egressCap hosts in the window; first=true for the first refusal over the cap (record one
// rate-limited event). Repeats and the rest are dropped by the caller and counted in EgressDropped. State of older
// windows is forgotten; event names are deterministic, so a restart re-creates nothing.
func (p *ExecutorPoller) admitEgress(run, host string, win time.Time) (rec, first bool) {
	if p.egressAgg == nil {
		p.egressAgg = map[string]*egressAgg{}
	}
	for k, a := range p.egressAgg {
		if win.Sub(a.win) >= p.egressWindow() {
			delete(p.egressAgg, k)
		}
	}
	a := p.egressAgg[run]
	if a == nil || !a.win.Equal(win) {
		if a != nil && a.win.After(win) { // an older line (another proxy replica lags): judge it by the newer window
			win = a.win
		} else {
			a = &egressAgg{win: win, hosts: map[string]bool{}}
			p.egressAgg[run] = a
		}
	}
	if a.hosts[host] {
		return false, false
	}
	if len(a.hosts) < p.egressCap() {
		a.hosts[host] = true
		return true, false
	}
	if a.limited {
		return false, false
	}
	a.limited = true
	return false, true
}

// recordSpec writes one executor SecurityEvent in the agents namespace (idempotent by name).
func (p *ExecutorPoller) recordSpec(ctx context.Context, spec v1.SecurityEventSpec) error {
	ev := &v1.SecurityEvent{ObjectMeta: metav1.ObjectMeta{Name: eventName(spec), Namespace: p.C.AgentsNS,
		Labels: map[string]string{"agent": spec.Agent, "agentdev/severity": spec.Severity, "agentdev/job": spec.Job,
			"agentdev/source": spec.Source}}, Spec: spec}
	if err := p.Create(ctx, ev); err != nil && !apierrors.IsAlreadyExists(err) {
		return err
	}
	return nil
}
