package main

// Per-agent egress hosts (#599). The agents' egress proxy (manifests/egress.yaml.tmpl) allows every agent the
// instance-wide list (EGRESS_HOSTS). An Agent with spec.egressHosts may reach those hosts too, and no other agent may,
// the same way an Executor gets its own hosts (executor_egress.go):
//
//   - the operator keeps Secret egress-agent-proxy in the agents namespace: one random key per agent with
//     spec.egressHosts (key-<name>) and the Squid include acl.conf that binds the proxy credential agent-<name>:<key>
//     to the agent's own hosts. The proxy reloads when acl.conf changes. The include comes after the forge and setup
//     denies, so a listed forge or setup host stays closed to the agent container.
//   - the operator copies the agent's key to Secret agent-<name>-egress-proxy, and the agent container's proxy URL
//     carries it (expanded by the kubelet). The key opens only this agent's own hosts, so the model that can read it
//     gains nothing it does not have already. The forge sidecar and the init container keep their own credentials.
//   - an agent without spec.egressHosts has no key, no rule and the pod it had before.

import (
	"context"
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"fmt"
	"regexp"
	"sort"
	"strings"

	corev1 "k8s.io/api/core/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/types"
	"sigs.k8s.io/controller-runtime/pkg/client"

	v1 "github.com/valentinalexeev/agentdev/images/operator/api/v1alpha1"
)

// +kubebuilder:rbac:groups="",resources=secrets,verbs=get;update,resourceNames=egress-agent-proxy

const (
	agentEgressSecret = "egress-agent-proxy" // operator-owned: per-agent keys and the Squid acl include
	agentEgressACL    = "acl.conf"
)

// agentEgressSecretName: the agent's copy of its own key, read only by the agent container's proxy URL.
func agentEgressSecretName(agent string) string { return "agent-" + agent + "-egress-proxy" }

// defaultClaudeUpstreamHost is the Claude API host that only claude-proxy may reach while the credential proxy is on
// (R64), unless CLAUDE_UPSTREAM_HOST names another (the same value as the playbook's claude_proxy_upstream_host).
const defaultClaudeUpstreamHost = "api.anthropic.com"

func (r *AgentReconciler) claudeUpstreamHost() string {
	if h := strings.ToLower(strings.TrimSpace(r.D.ClaudeUpstreamHost)); h != "" {
		return h
	}
	return defaultClaudeUpstreamHost
}

// coversHost: the Squid dstdomain entry h matches the name host ("x.org" that name, ".x.org" x.org and subdomains).
func coversHost(h, host string) bool {
	if strings.HasPrefix(h, ".") {
		return host == h[1:] || strings.HasSuffix(host, h)
	}
	return h == host
}

// agentEgressHosts is the sorted list of an agent's own hosts (spec.egressHosts). Invalid entries are dropped
// (fail closed if the CRD was changed or bypassed). With the credential proxy on, an entry that covers the Claude API
// is dropped too: an agent's own hosts never reopen the path around claude-proxy (R64).
func (r *AgentReconciler) agentEgressHosts(a *v1.Agent) []string {
	seen := map[string]bool{}
	var out []string
	for _, h := range a.Spec.EgressHosts {
		h = strings.ToLower(strings.TrimSpace(h))
		if !egressHostRE.MatchString(h) || len(h) > 253 || seen[h] {
			continue
		}
		if r.D.ClaudeProxyURL != "" && coversHost(h, r.claudeUpstreamHost()) {
			continue
		}
		seen[h] = true
		out = append(out, h)
	}
	sort.Strings(out)
	return out
}

// hasOwnEgress: the agent gets its own proxy credential (spec.egressHosts with at least one valid host, a proxy, and
// a name whose key Secret cannot be another agent's Claude proxy key, see egressNameOK).
func (r *AgentReconciler) hasOwnEgress(a *v1.Agent) bool {
	return r.D.EgressProxy != "" && egressNameOK(a.Name) && len(r.agentEgressHosts(a)) > 0
}

// egressNameOK: agent-<name>-egress-proxy is also the name of the Claude proxy key of an agent named <name>-egress
// (agent-<name>-egress + -proxy). The CRD refuses names ending in -egress; this is the second line (fail closed).
func egressNameOK(name string) bool {
	return execNameRE.MatchString(name) && !strings.HasSuffix(name, "-egress")
}

// agentEgressRules renders the Squid include for the given agents and keys. Only lines this function writes reach
// squid.conf: names match the agent name rule, hosts egressHostRE, keys are hex.
func (r *AgentReconciler) agentEgressRules(agents []v1.Agent, keys map[string]string) string {
	var b strings.Builder
	b.WriteString("# generated by agentdev-operator (#599): one credential and host list per Agent with spec.egressHosts\n")
	for i := range agents {
		a := &agents[i]
		k := keys[a.Name]
		hs := r.agentEgressHosts(a)
		if !hexKeyRE.MatchString(k) || len(hs) == 0 || !egressNameOK(a.Name) {
			continue
		}
		id := strings.ReplaceAll(a.Name, "-", "_")
		cred := regexp.QuoteMeta(base64.StdEncoding.EncodeToString([]byte("agent-" + a.Name + ":" + k)))
		fmt.Fprintf(&b, "acl agent_%s_client req_header Proxy-Authorization ^Basic.%s$\n", id, cred)
		fmt.Fprintf(&b, "acl agent_%s_hosts dstdomain -n %s\n", id, strings.Join(hs, " "))
		fmt.Fprintf(&b, "http_access allow agent_%s_client agent_%s_hosts\n", id, id)
	}
	return b.String()
}

// syncAgentEgress keeps Secret egress-agent-proxy in step with the Agents of the namespace (a key for each agent with
// own hosts, kept across passes; none for others; and acl.conf), then writes the reconciled agent's copy of its key.
// Off without a proxy. a is nil for a deleted agent: its key and rule are dropped.
func (r *AgentReconciler) syncAgentEgress(ctx context.Context, ns string, a *v1.Agent) error {
	if r.D.EgressProxy == "" {
		return nil
	}
	rd := r.Direct
	if rd == nil {
		rd = r.Client
	}
	var sec corev1.Secret
	err := rd.Get(ctx, types.NamespacedName{Namespace: ns, Name: agentEgressSecret}, &sec)
	create := apierrors.IsNotFound(err)
	if err != nil && !create {
		return fmt.Errorf("agent egress secret: %w", err)
	}
	if create && (a == nil || !r.hasOwnEgress(a)) {
		return nil // nothing to write yet; the proxy starts with an empty include
	}
	var list v1.AgentList
	if err := r.List(ctx, &list, client.InNamespace(ns)); err != nil {
		return fmt.Errorf("list agents: %w", err)
	}
	var live []v1.Agent
	keys := map[string]string{}
	for i := range list.Items {
		x := list.Items[i]
		if a != nil && x.Name == a.Name {
			x = *a // the object this pass reconciles, not a cache that may lag
		}
		if !x.DeletionTimestamp.IsZero() || !r.hasOwnEgress(&x) || !execNameRE.MatchString(x.Name) {
			continue
		}
		k := string(sec.Data["key-"+x.Name])
		if !hexKeyRE.MatchString(k) {
			var b [24]byte
			if _, err := rand.Read(b[:]); err != nil {
				return err
			}
			k = hex.EncodeToString(b[:])
		}
		keys[x.Name] = k
		live = append(live, x)
	}
	sort.Slice(live, func(i, j int) bool { return live[i].Name < live[j].Name })
	data := map[string][]byte{agentEgressACL: []byte(r.agentEgressRules(live, keys))}
	for n, k := range keys {
		data["key-"+n] = []byte(k)
	}
	switch {
	case create:
		sec = corev1.Secret{ObjectMeta: metav1.ObjectMeta{Name: agentEgressSecret, Namespace: ns,
			Labels: map[string]string{"app": "egress-proxy"}}, Data: data}
		if err := r.Create(ctx, &sec); err != nil {
			return fmt.Errorf("agent egress secret: %w", err)
		}
	case !equalBytes(sec.Data, data):
		sec.Data, sec.StringData = data, nil
		if err := r.Update(ctx, &sec); err != nil {
			return fmt.Errorf("agent egress secret: %w", err)
		}
	}
	if a == nil || keys[a.Name] == "" {
		return nil
	}
	if err := applyAgentSecret(ctx, r.Client, a, agentEgressSecretName(a.Name), map[string][]byte{"password": []byte(keys[a.Name])}); err != nil {
		return fmt.Errorf("agent egress key secret: %w", err)
	}
	return nil
}
