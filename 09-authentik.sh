#!/usr/bin/env bash
# authentik (#45, #12): the instance's identity provider, in namespace ${PLATFORM_NS}, on the platform Postgres (08).
#   ./run.sh 09      deploy (idempotent, after 08)
# The first admin (akadmin) is the owner: its password is generated into .secrets/platform/authentik-admin.
# No Redis: authentik >= 2025.10 keeps cache, sessions and tasks in Postgres.
source "$(dirname "$0")/lib.sh"
need helm; need openssl

S="${SPIKE_DIR}/.secrets/platform"; mkdir -p "${S}"; chmod 700 "${S}"
sec() { [[ -s "${S}/$1" ]] || { openssl rand -hex 24 > "${S}/$1"; chmod 600 "${S}/$1"; }; cat "${S}/$1"; }
k -n "${PLATFORM_NS}" get statefulset platform-db >/dev/null 2>&1 || die "platform Postgres not deployed: run ./run.sh 08 first"

log "Database"
# init.sql only runs on an empty volume: create the role and database here too, for an existing platform
# generated by sec(): hex only, so safe to inline in SQL
pgpw=$(sec pg-authentik)
k -n "${PLATFORM_NS}" exec -i platform-db-0 -- psql -U postgres -v ON_ERROR_STOP=1 -q >/dev/null <<SQL
SELECT 'CREATE ROLE authentik LOGIN' WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname='authentik')\gexec
ALTER ROLE authentik PASSWORD '${pgpw}';
SELECT 'CREATE DATABASE authentik OWNER authentik' WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname='authentik')\gexec
SQL
ok "database authentik"

log "authentik ${AUTHENTIK_VERSION} (${PLATFORM_NS})"
# configuration as one Secret (authentik reads AUTHENTIK_* env); stdin, never argv
{ printf 'AUTHENTIK_SECRET_KEY=%s\n' "$(sec authentik-secret-key)$(sec authentik-secret-key2)"
  printf 'AUTHENTIK_POSTGRESQL__HOST=platform-db\nAUTHENTIK_POSTGRESQL__NAME=authentik\nAUTHENTIK_POSTGRESQL__USER=authentik\n'
  printf 'AUTHENTIK_POSTGRESQL__PASSWORD=%s\n' "${pgpw}"
  printf 'AUTHENTIK_BOOTSTRAP_PASSWORD=%s\n' "$(sec authentik-admin)"
  printf 'AUTHENTIK_BOOTSTRAP_EMAIL=%s\n' "${AUTHENTIK_ADMIN_EMAIL}"
  printf 'AUTHENTIK_ERROR_REPORTING__ENABLED=false\nAUTHENTIK_DISABLE_UPDATE_CHECK=true\n'
} | k -n "${PLATFORM_NS}" create secret generic authentik --from-env-file=/dev/stdin --dry-run=client -o yaml \
  | k apply --server-side --force-conflicts --field-manager=agentdev -f - >/dev/null

helm repo add authentik https://charts.goauthentik.io >/dev/null 2>&1 || true
# blueprints: agentdev's own authentik objects (the OIDC application #46, the group agentdev-admins #100), mounted
# into the worker by the chart. They create the group, but never set its members: authentik re-applies blueprints, and
# a member list in a blueprint would remove each admin that a person added (docs/admin.md, docs/security.md R53)
bp=(); for f in "${SPIKE_DIR}"/manifests/authentik-blueprint-*.yaml; do bp+=("--from-file=${f}"); done
k -n "${PLATFORM_NS}" create configmap authentik-blueprints --dry-run=client -o yaml "${bp[@]}" \
  | k apply --server-side --force-conflicts --field-manager=agentdev -f - >/dev/null
helm repo update authentik >/dev/null
helm --kube-context "kind-${CLUSTER_NAME}" upgrade --install authentik authentik/authentik \
  --namespace "${PLATFORM_NS}" --version "${AUTHENTIK_VERSION}" \
  -f "${SPIKE_DIR}/manifests/authentik-values.yaml" --wait --timeout 15m >/dev/null
ok "authentik ready"

log "agentdev-admins (#100)"
# kind only (run.sh is kind-only, helm uses the kind context): add the local owner akadmin to agentdev-admins once,
# so the e2e has an admin. POST /api/v3/core/groups/{pk}/add_user/ only adds: it never removes a member, and a second
# run is a no-op. Then a check: a member added by a person (a test user) survives a blueprint re-apply.
# Runs in the worker pod (it mounts the blueprints) through the authentik REST API in-process, as akadmin: no token
# is created or printed.
ak_py=$(cat <<'PY'
import sys, time
from rest_framework.test import APIClient
from authentik.core.models import Group, User
from authentik.blueprints.models import BlueprintInstance
from authentik.blueprints.v1.importer import Importer
for _ in range(60):
    g = Group.objects.filter(name="agentdev-admins").first()
    if g: break
    time.sleep(5)
else: sys.exit("group agentdev-admins missing: blueprint not applied")
admin = User.objects.get(username="akadmin")
c = APIClient(); c.force_authenticate(admin)
api = "/api/v3/core/groups/%s/" % g.pk
def call(op, pk):
    r = c.post(api + op + "/", {"pk": pk}, format="json")
    if r.status_code != 204: sys.exit("group %s: HTTP %s" % (op, r.status_code))
def add(pk): call("add_user", pk)
def members(): g.refresh_from_db(); return set(g.users.values_list("username", flat=True))
test = None
try:
    add(admin.pk)
    print("akadmin in agentdev-admins")
    test, _ = User.objects.get_or_create(username="agentdev-09-membership-test", defaults={"name": "09 test", "is_active": False})
    add(test.pk)
    # the old kind blueprint (before #103 review) set the members: forget its instance, its file is gone
    BlueprintInstance.objects.filter(path__endswith="authentik-blueprint-local-admin.yaml").delete()
    applied = 0
    for b in BlueprintInstance.objects.filter(path__contains="authentik-blueprint-"):
        imp = Importer.from_string(b.retrieve(), b.context)
        ok, logs = imp.validate()
        if not ok or not imp.apply(): sys.exit("blueprint %s did not apply" % b.path)
        applied += 1
    if not applied: sys.exit("no agentdev blueprint found to re-apply")
    m = members()
    if not {"akadmin", test.username} <= m: sys.exit("re-apply removed members: %s" % sorted(m))
    print("check: members kept after re-applying %d blueprint(s)" % applied)
finally:
    if test:
        call("remove_user", test.pk)
        test.delete()
PY
)
k -n "${PLATFORM_NS}" exec deploy/authentik-worker -- ak shell -c "${ak_py}" 2>&1 | grep -E '^(akadmin|check|group|blueprint|re-apply|no agentdev|Traceback|[A-Za-z.]*Error)' \
  | sed 's/^/  /'; [[ ${PIPESTATUS[0]} -eq 0 ]] || die "agentdev-admins: setup or membership check failed"
ok "akadmin in agentdev-admins; members survive a blueprint re-apply"
record "authentik ${AUTHENTIK_VERSION} up in ${PLATFORM_NS}"
echo "  UI: ${KUBECTL} -n ${PLATFORM_NS} port-forward svc/authentik-server 9443:443  ->  https://localhost:9443/ (https: session cookies)"
echo "      login akadmin, password: .secrets/platform/authentik-admin"

# ---- company SSO (#122) ----
# kind: a local OIDC stand-in plays Google Workspace (manifests/kind/sso-standin.yaml); the same blueprint and property
# mappings as GKE (manifests/authentik-blueprint-sso.yaml) turn it into the source `agentdev-sso`. SSO_STANDIN=0 skips.
if [[ "${SSO_STANDIN:-1}" == 1 ]]; then
  log "Company SSO stand-in (#122)"
  k apply --server-side --force-conflicts --field-manager=agentdev -f "${SPIKE_DIR}/manifests/kind/sso-standin.yaml" >/dev/null
  k -n "${PLATFORM_NS}" rollout status deploy/sso-standin --timeout=180s >/dev/null
  # same patterns as the playbook (infra/ansible/roles/authentik_sso): these values go into blueprint expressions
  admin_group="${SSO_ADMIN_GROUP:-agentdev-admins@example.com}"; forge_attr="${SSO_FORGE_ATTR:-forgeLogin}"
  forge_attr_github="${SSO_FORGE_ATTR_GITHUB:-githubLogin}"; forge_attr_gitea="${SSO_FORGE_ATTR_GITEA:-giteaLogin}"
  [[ "${admin_group}" =~ ^[A-Za-z0-9._@+-]{1,128}$ ]] || die "SSO_ADMIN_GROUP: letters, digits and ._@+- only"
  domains="${SSO_ALLOWED_DOMAINS:-example.com}"
  [[ "${domains}" =~ ^[a-z0-9]([a-z0-9.-]{0,252})(,[a-z0-9]([a-z0-9.-]{0,252}))*$ ]] || die "SSO_ALLOWED_DOMAINS: comma-separated lower-case domains"
  for a in "${forge_attr}" "${forge_attr_github}" "${forge_attr_gitea}"; do
    [[ "${a}" =~ ^[A-Za-z][A-Za-z0-9_.]{0,63}$ ]] || die "SSO_FORGE_ATTR*: an attribute name"
  done
  inner="http://sso-standin.${PLATFORM_NS}.svc.cluster.local:8080/default"
  { printf 'AGENTDEV_SSO_OIDC=true\nAGENTDEV_SSO_NAME=Company SSO (local stand-in)\n'
    printf 'AGENTDEV_SSO_ADMIN_GROUP=%s\nAGENTDEV_SSO_FORGE_ATTR=%s\nAGENTDEV_SSO_ALLOWED_DOMAINS=%s\n' "${admin_group}" "${forge_attr}" "${domains}"
    printf 'AGENTDEV_SSO_FORGE_ATTR_GITHUB=%s\nAGENTDEV_SSO_FORGE_ATTR_GITEA=%s\n' "${forge_attr_github}" "${forge_attr_gitea}"
    printf 'AGENTDEV_SSO_OIDC_CLIENT_ID=authentik\nAGENTDEV_SSO_OIDC_CLIENT_SECRET=%s\n' "$(sec sso-standin-client-secret)"
    printf 'AGENTDEV_SSO_OIDC_AUTHORIZE_URL=http://localhost:18080/default/authorize\n'   # the browser, port-forward
    printf 'AGENTDEV_SSO_OIDC_TOKEN_URL=%s/token\nAGENTDEV_SSO_OIDC_USERINFO_URL=%s/userinfo\n' "${inner}" "${inner}"
  } | k -n "${PLATFORM_NS}" create secret generic authentik-sso --from-env-file=/dev/stdin --dry-run=client -o yaml \
    | k apply --server-side --force-conflicts --field-manager=agentdev -f - >/dev/null
  # envFrom is read at pod start: restart when the Secret changed (hash only, never the values)
  h=$(k -n "${PLATFORM_NS}" get secret authentik-sso -o jsonpath='{.data}' | openssl dgst -sha256 -r | cut -c1-16)
  for d in authentik-server authentik-worker; do
    [[ "$(k -n "${PLATFORM_NS}" get deploy "${d}" -o jsonpath='{.spec.template.metadata.annotations.agentdev/sso-hash}')" == "${h}" ]] \
      || k -n "${PLATFORM_NS}" patch deploy "${d}" --type merge \
           -p "{\"spec\":{\"template\":{\"metadata\":{\"annotations\":{\"agentdev/sso-hash\":\"${h}\"}}}}}" >/dev/null
  done
  for d in authentik-server authentik-worker; do k -n "${PLATFORM_NS}" rollout status "deploy/${d}" --timeout=600s >/dev/null; done
  # the worker re-applies a blueprint only when its file changes, not when its env does: apply the SSO one now
  wp=$(k -n "${PLATFORM_NS}" get pod -l app.kubernetes.io/name=authentik,app.kubernetes.io/component=worker \
       --field-selector=status.phase=Running -o jsonpath='{.items[0].metadata.name}')
  # a changed ConfigMap reaches the mounted file after up to a minute: wait for the repo version
  want=$(openssl dgst -sha256 -r "${SPIKE_DIR}/manifests/authentik-blueprint-sso.yaml" | cut -d' ' -f1)
  for _ in $(seq 1 60); do
    have=$(k -n "${PLATFORM_NS}" exec "${wp}" -- cat /blueprints/mounted/cm-authentik-blueprints/authentik-blueprint-sso.yaml 2>/dev/null \
           | openssl dgst -sha256 -r | cut -d' ' -f1)
    [[ "${have}" == "${want}" ]] && break; sleep 3
  done
  [[ "${have}" == "${want}" ]] || die "the SSO blueprint did not reach the authentik worker"
  k -n "${PLATFORM_NS}" exec -i "${wp}" -- ak shell 2>/dev/null <<'PY' | grep -q '^SSO_APPLIED=True$' || die "SSO blueprint did not apply (authentik admin: System > Blueprints)"
from authentik.blueprints.models import BlueprintInstance
from authentik.blueprints.v1.importer import Importer
bi = BlueprintInstance.objects.get(path="mounted/cm-authentik-blueprints/authentik-blueprint-sso.yaml")
print("SSO_APPLIED=" + str(Importer.from_string(bi.retrieve(), bi.context).apply()))
PY
  ok "stand-in up, source agentdev-sso configured by the blueprint"
  # sign-in checks: add, keep a hand-added member, remove only on leaving the directory group, audit (#122)
  if [[ "${SSO_CHECK:-1}" == 1 ]]; then
    need python3
    python3 "${SPIKE_DIR}/scripts/sso-check.py" --context "kind-${CLUSTER_NAME}" --namespace "${PLATFORM_NS}" \
      --admin-group "${admin_group}" --forge-attr "${forge_attr}" --forge-attr-github "${forge_attr_github}" --forge-attr-gitea "${forge_attr_gitea}" --domain "${domains%%,*}" || die "SSO check failed"
    ok "SSO check passed"
    record "authentik SSO stand-in: group sync and forge_login checked"
  fi
fi
